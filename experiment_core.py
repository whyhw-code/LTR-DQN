def esg_metrics(
    market: str,
    actions: pd.DataFrame,
    threshold: float,
    prefilter: bool,
) -> dict[str, float]:
    code = MARKETS.get(market, market)
    esg_file = DATA_DIR / "ESG" / f"{code}temp_test_ndcg_train3_esg.csv"
    if not esg_file.is_file():
        raise FileNotFoundError(f"T7 ESG data not found: {esg_file}")
    # T7M4-T7M7/T7C4-T7C7 rank directly with the prediction stored in the
    # ESG input. Replacing it with a newly trained ranker's prediction changes
    # the experiment and can strongly inflate the PI portfolios.
    frame = pd.read_csv(esg_file)
    required = {"qid_date", "stock_code", "prediction", "ESG", "pclose", "close"}
    missing = sorted(required - set(frame.columns))
    if missing:
        raise ValueError(f"T7 ESG data is missing required columns {missing}: {esg_file}")
    actions = actions[["qid_date", "real_action"]].copy()
    actions["real_action"] = pd.to_numeric(actions["real_action"], errors="coerce").fillna(0)
    capital = 1_000_000.0
    rows = []
    selected = wins = 0
    for date, group in frame.groupby("qid_date", sort=True):
        top_n_row = actions.loc[actions.qid_date == date, "real_action"]
        if top_n_row.empty:
            continue
        top_n = int(top_n_row.iloc[0])
        if prefilter:
            subset = group[group.ESG >= threshold]
            chosen = subset.nlargest(min(top_n, len(subset)), "prediction")
        else:
            chosen = group.nlargest(min(top_n, len(group)), "prediction")
            chosen = chosen[chosen.ESG >= threshold]
        if chosen.empty:
            rows.append({"qid_date": date, "funds": capital, "day_return": 0.0})
            continue
        selected += len(chosen)
        allocation = capital / len(chosen)
        total = 0.0
        for _, row in chosen.iterrows():
            lots = int(allocation / (100 * row.pclose))
            fee = lots * 100 * row.pclose * FEES
            shares = int((allocation - fee) / (100 * row.pclose)) * 100
            cash = allocation - fee - shares * row.pclose
            sell = shares * row.close - shares * row.close * (FEES + STAMP_TAX) + cash
            total += sell
            wins += int(sell > allocation)
        rows.append({"qid_date": date, "funds": total, "day_return": (total - capital) / capital})
        capital = total
    daily = pd.DataFrame(rows)
    arr = (daily.iloc[-1].funds / 1_000_000) ** (242 / len(daily)) - 1
    dd = (daily.funds - daily.funds.cummax()) / daily.funds.cummax()
    mdr = -float(dd.min())
    cr = arr / mdr if mdr else np.nan
    std = daily.day_return.std()
    sr = (((1 + daily.day_return.mean()) ** 242 - 1 - 0.025) / (std * 242 ** 0.5)) if std else np.nan
    return {"ARR": float(arr), "MDR": float(mdr), "CR": float(cr), "SR": float(sr), "WR": float(wins / selected) if selected else np.nan}


def _paper_table(subset: pd.DataFrame, table: str) -> pd.DataFrame:
    index_columns = ["model"] if table != "T5" else ["train_year", "model"]
    values = subset.pivot_table(
        index=index_columns,
        columns="market",
        values=METRIC_NAMES,
        aggfunc="first",
        dropna=False,
    )
    markets = [market for market in MARKETS if market in subset["market"].unique()]
    metric_columns = [(metric, market) for market in markets for metric in METRIC_NAMES]
    values = values.reindex(columns=pd.MultiIndex.from_tuples(metric_columns))
    values.columns = [f"{market} {metric}" for metric, market in values.columns]
    values = values.reset_index()
    values["model"] = values["model"].replace(PAPER_MODEL_NAMES)
    order = {name: position for position, name in enumerate(TABLE_MODEL_ORDER[table])}
    values["_model_order"] = values["model"].map(order).fillna(len(order))
    sort_columns = ["_model_order"] if table != "T5" else ["train_year", "_model_order"]
    values = values.sort_values(sort_columns, kind="stable").drop(columns="_model_order")
    rename = {"model": "Model"}
    if table == "T5":
        rename["train_year"] = "Training duration"
        values["train_year"] = values["train_year"].map(lambda value: f"{int(value)} years")
    values = values.rename(columns=rename)
    if table == "T4":
        categories = {
            "Market indices": "Benchmarks",
            "Baseline portfolios": "Benchmarks",
            "LR": "Comparison models",
            "MLP_R": "Comparison models",
            "SVM_R": "Comparison models",
            "XGB_R": "Comparison models",
            "SVM_C": "Comparison models",
            "MLP_C": "Comparison models",
            "XGB_C": "Comparison models",
            "LambdaRank": "Main models",
            "LambdaMART": "Main models",
            "LTR-DQN": "Main models",
        }
        values.insert(0, "Category", values["Model"].map(categories))
    return values


def _paper_headers(table: str, markets: list[str]) -> list[list[str]]:
    if table == "T5":
        leading = ["Training duration", "Model"]
        market_labels = {"Main": "Main Board", "ChiNext": "ChiNext"}
    elif table == "T4":
        leading = ["", "Models"]
        market_labels = {"Main": "Main board market", "ChiNext": "ChiNext market"}
    else:
        leading = ["Models"]
        market_labels = {"Main": "Main board market", "ChiNext": "ChiNext market"}
    top = list(leading)
    bottom = list(leading)
    for market in markets:
        top.extend([market_labels[market]] * len(METRIC_NAMES))
        bottom.extend(METRIC_NAMES)
    return [top, bottom]


def _paper_rows(subset: pd.DataFrame, table: str) -> tuple[list[list[str]], list[list[Any]]]:
    markets = [market for market in MARKETS if market in subset["market"].unique()]
    paper = _paper_table(subset, table)
    rows = paper.astype(object).where(pd.notna(paper), "").values.tolist()
    if table in {"T4", "T5"}:
        previous = None
        for row in rows:
            current = row[0]
            if current == previous:
                row[0] = ""
            elif current != "":
                previous = current
    return _paper_headers(table, markets), rows


def _write_paper_csv(path: Path, headers: list[list[str]], rows: list[list[Any]]) -> None:
    import csv

    with path.open("w", encoding="utf-8-sig", newline="") as stream:
        writer = csv.writer(stream)
        writer.writerows(headers)
        for row in rows:
            writer.writerow([
                f"{value:.3f}" if isinstance(value, (float, np.floating)) else value
                for value in row
            ])


def _merge_repeated_labels(worksheet, rows: list[list[Any]], start_row: int = 3) -> None:
    group_start = None
    for offset, row in enumerate(rows):
        excel_row = start_row + offset
        if row[0] != "":
            if group_start is not None and excel_row - 1 > group_start:
                worksheet.merge_cells(start_row=group_start, start_column=1, end_row=excel_row - 1, end_column=1)
            group_start = excel_row
    final_row = start_row + len(rows) - 1
    if group_start is not None and final_row > group_start:
        worksheet.merge_cells(start_row=group_start, start_column=1, end_row=final_row, end_column=1)


def _write_paper_sheet(worksheet, table: str, headers: list[list[str]], rows: list[list[Any]]) -> None:
    from openpyxl.utils import get_column_letter
    from openpyxl.styles import Alignment, Border, Font, Side

    for row in headers + rows:
        worksheet.append(row)
    leading_columns = 2 if table in {"T4", "T5"} else 1
    market_count = (len(headers[0]) - leading_columns) // len(METRIC_NAMES)
    for market_index in range(market_count):
        start = leading_columns + 1 + market_index * len(METRIC_NAMES)
        worksheet.merge_cells(
            start_row=1, start_column=start,
            end_row=1, end_column=start + len(METRIC_NAMES) - 1,
        )
    if table in {"T4", "T5"}:
        _merge_repeated_labels(worksheet, rows)
    worksheet.freeze_panes = "A3"
    worksheet.sheet_view.showGridLines = False
    thin = Side(style="thin", color="808080")
    medium = Side(style="medium", color="000000")
    for cell in worksheet[1]:
        cell.font = Font(bold=True)
        cell.alignment = Alignment(horizontal="center", vertical="center")
        cell.border = Border(top=medium)
    for cell in worksheet[2]:
        cell.font = Font(bold=True)
        cell.alignment = Alignment(horizontal="center", vertical="center")
        cell.border = Border(bottom=medium)
    for row in worksheet.iter_rows(min_row=3):
        for column, cell in enumerate(row, start=1):
            cell.alignment = Alignment(
                horizontal="left" if column <= leading_columns else "right",
                vertical="center",
            )
            cell.border = Border(bottom=thin)
            if isinstance(cell.value, (int, float)):
                cell.number_format = "0.000"
    worksheet.row_dimensions[1].height = 22
    worksheet.row_dimensions[2].height = 22
    for column in range(1, leading_columns + 1):
        worksheet.column_dimensions[get_column_letter(column)].width = 20
    for column in range(leading_columns + 1, len(headers[0]) + 1):
        worksheet.column_dimensions[get_column_letter(column)].width = 10


def _format_worksheet(worksheet, table: str) -> None:
    from openpyxl.styles import Alignment, Border, Font, PatternFill, Side

    worksheet.freeze_panes = "A2"
    worksheet.sheet_view.showGridLines = False
    header_fill = PatternFill("solid", fgColor="1F4E78")
    header_font = Font(color="FFFFFF", bold=True)
    bottom = Border(bottom=Side(style="thin", color="A6A6A6"))
    for cell in worksheet[1]:
        cell.fill = header_fill
        cell.font = header_font
        cell.alignment = Alignment(horizontal="center")
    for row in worksheet.iter_rows(min_row=2):
        for cell in row:
            cell.border = bottom
            if isinstance(cell.value, (int, float)):
                cell.number_format = "0.000"
    for column in worksheet.columns:
        width = min(max(len(str(cell.value or "")) for cell in column) + 2, 22)
        worksheet.column_dimensions[column[0].column_letter].width = width
    worksheet.auto_filter.ref = worksheet.dimensions


def _write_t6_sheet(worksheet, subset: pd.DataFrame) -> None:
    """Write the sampling summary in the manuscript's Table 6 layout."""
    rates = ["100%", "90%", "80%", "70%", "60%", "50%"]
    headers = [
        ["Markets", "Model", "ARR"] + ["Sampling rates"] * len(rates),
        ["Markets", "Model", "ARR"] + rates,
    ]
    rows = []
    markets = [market for market in ("Main", "ChiNext") if market in set(subset.get("market", []))]
    for market in markets:
        market_rows = subset[subset["market"] == market]
        for model in ("LambdaRank", "LambdaMART", "LTR-DQN"):
            model_rows = market_rows[market_rows["model"] == model]
            for statistic in ("Mean", "Std."):
                row = [market if statistic == "Mean" and model == "LambdaRank" else "", model, statistic]
                for rate in rates:
                    value = model_rows.loc[model_rows["statistic"] == statistic, rate]
                    row.append(value.iloc[0] if not value.empty else "")
                rows.append(row)
    for row in headers + rows:
        worksheet.append(row)
    worksheet.merge_cells(start_row=1, start_column=4, end_row=1, end_column=3 + len(rates))
    # Each market occupies six model/statistic rows, matching the paper table.
    for market_index in range(len(markets)):
        start = 3 + market_index * 6
        worksheet.merge_cells(start_row=start, start_column=1, end_row=start + 5, end_column=1)
    worksheet.freeze_panes = "A3"
    worksheet.sheet_view.showGridLines = False
    from openpyxl.styles import Alignment, Border, Font, Side
    from openpyxl.utils import get_column_letter
    thin = Side(style="thin", color="808080")
    medium = Side(style="medium", color="000000")
    for cell in worksheet[1]:
        cell.font = Font(bold=True)
        cell.alignment = Alignment(horizontal="center", vertical="center")
        cell.border = Border(top=medium)
    for cell in worksheet[2]:
        cell.font = Font(bold=True)
        cell.alignment = Alignment(horizontal="center", vertical="center")
        cell.border = Border(bottom=medium)
    for row in worksheet.iter_rows(min_row=3):
        for column, cell in enumerate(row, start=1):
            cell.alignment = Alignment(horizontal="left" if column <= 3 else "right", vertical="center")
            cell.border = Border(bottom=thin)
            if isinstance(cell.value, (int, float)):
                cell.number_format = "0.000"
    worksheet.column_dimensions["A"].width = 20
    worksheet.column_dimensions["B"].width = 18
    worksheet.column_dimensions["C"].width = 10
    for column in range(4, 4 + len(rates)):
        worksheet.column_dimensions[get_column_letter(column)].width = 10


def _stabilize_xlsx(path: Path) -> None:
    """Normalize ZIP metadata so repeated XLSX exports have one byte hash."""
    temporary = path.with_name(path.name + ".tmp")
    fixed_time = (2000, 1, 1, 0, 0, 0)
    with ZipFile(path, "r") as source, ZipFile(temporary, "w", ZIP_DEFLATED) as target:
        for info in source.infolist():
            entry = ZipInfo(info.filename, date_time=fixed_time)
            entry.compress_type = ZIP_DEFLATED
            entry.external_attr = info.external_attr
            entry.comment = info.comment
            target.writestr(entry, source.read(info.filename))
    temporary.replace(path)


def write_results(
    records: list[dict[str, Any]],
    csv_path: Path | None,
    excel_path: Path,
    *,
    write_table_csvs: bool = True,
    float_format: str | None = None,
) -> dict[str, str]:
    excel_path.parent.mkdir(parents=True, exist_ok=True)
    frame = pd.DataFrame(records)
    if csv_path is not None:
        csv_path.parent.mkdir(parents=True, exist_ok=True)
        frame.to_csv(
            csv_path, index=False, encoding="utf-8-sig", float_format=float_format
        )
    paper_csvs: dict[str, str] = {}
    with pd.ExcelWriter(excel_path, engine="openpyxl") as writer:
        # Keep the workbook byte-stable across repeated exports. The table
        # values are already deterministic; openpyxl otherwise injects the
        # current timestamp into docProps/core.xml.
        fixed_timestamp = datetime(2000, 1, 1, 0, 0, 0)
        writer.book.properties.creator = "LTR-DQN reproduction"
        writer.book.properties.lastModifiedBy = "LTR-DQN reproduction"
        writer.book.properties.created = fixed_timestamp
        writer.book.properties.modified = fixed_timestamp
        for table in ("T3", "T4", "T5", "T7", "T6"):
            subset = frame[frame["table"] == table].copy()
            if subset.empty:
                continue
            if table == "T6":
                subset.drop(columns=["table"], errors="ignore").to_csv(
                    excel_path.parent / "T6_summary.csv",
                    index=False,
                    encoding="utf-8-sig",
                    float_format=float_format,
                )
                worksheet = writer.book.create_sheet("T6_sampling")
                _write_t6_sheet(worksheet, subset)
                continue
            headers, rows = _paper_rows(subset, table)
            if write_table_csvs:
                table_csv = excel_path.parent / f"{table}.csv"
                _write_paper_csv(table_csv, headers, rows)
                paper_csvs[table] = str(table_csv)
            worksheet = writer.book.create_sheet(table)
            _write_paper_sheet(worksheet, table, headers, rows)
    _stabilize_xlsx(excel_path)
    return paper_csvs


