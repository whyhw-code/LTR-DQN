def artifact_dir(run_dir: Path, kind: str) -> Path:
    """Resolve artifact folders for the clean package or a named run.

    The default clean-package layout keeps intermediates in ``temp`` and DQN
    checkpoints in ``model``.  Explicit run directories retain the historical
    self-contained ``rankings/models/actions/results`` layout.
    """
    root = Path(run_dir).resolve()
    if kind not in {"rankings", "models", "actions", "results"}:
        raise ValueError(f"Unknown artifact kind: {kind}")
    if root == CODE_DIR.resolve():
        return {
            "rankings": TEMP_DIR / "rankings",
            "models": MODEL_DIR,
            "actions": TEMP_DIR / "actions",
            "results": RESULTS_DIR,
        }[kind]
    return root / kind


def dqn_ranking_path(run_dir: Path, market: str, year: int, split: str) -> Path:
    """Return the LambdaMART ranking generated by the current training run.

    Strict reproduction must use the current run's train/test ranking outputs;
    silently falling back to the checked-in ``temp/oc/batch123`` snapshot would
    mix a new training run with an old test input.
    """
    if split not in {"train", "test"}:
        raise ValueError("split must be 'train' or 'test'")
    fresh = artifact_dir(run_dir, "rankings") / f"{market}_{DQN_RANKER}_{split}{year}.csv"
    if not fresh.is_file():
        raise FileNotFoundError(
            f"Fresh LambdaMART {split} ranking not found: {fresh}. "
            "Run train.py with --models rankers or --models all first."
        )
    return fresh


