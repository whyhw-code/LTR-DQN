def validate_runtime() -> None:
    configure_torch_threads(torch)
    actual = {
        "python": platform.python_version(),
        "numpy": np.__version__,
        "pandas": pd.__version__,
        "torch": torch.__version__,
        "xgboost": xgb.__version__,
    }
    mismatches = {
        name: (LOCKED_RUNTIME[name], value)
        for name, value in actual.items()
        if value != LOCKED_RUNTIME[name]
    }
    if mismatches:
        details = ", ".join(
            f"{name}={found!r} (required {expected!r})"
            for name, (expected, found) in mismatches.items()
        )
        raise RuntimeError(
            "Locked reproduction environment mismatch: " + details + ". "
            "Create the environment from requirements-lock.txt or environment.yml; "
            "the run was stopped before fitting any model."
        )


def load_stock_data(market: str, train_year: int) -> tuple[pd.DataFrame, pd.DataFrame]:
    code = MARKETS.get(market, market)
    frame = pd.read_csv(DATA_DIR / f"{code}merge_open_close_final.csv", usecols=STOCK_COLUMNS)
    train = frame[(frame.qid_date >= year_start(train_year)) & (frame.qid_date <= TRAIN_END)].copy()
    test = frame[(frame.qid_date >= TEST_START) & (frame.qid_date <= TEST_END)].copy()
    return train, test


def model_for_baseline(name: str, market: str, train_year: int, seed: int):
    code = MARKETS.get(market, market)
    if name == "LR":
        return Lasso(alpha=0.0001)
    if name == "MLP_R":
        # GitHub T4C3/T4C5 use a fixed implementation seed for the baseline.
        return MLPRegressor(hidden_layer_sizes=(24,), max_iter=100, random_state=42)
    if name == "SVM_R":
        return SVR(kernel="rbf", C=1.0)
    if name == "XGB_R":
        # Restore the estimator counts used by the original T5 entrypoints.
        # Year 3 retains the consolidated T4 configuration.
        xgb_r_estimators = {
            ("0060", 2): 300,
            ("3068", 2): 200,
            ("0060", 4): 100,
            ("3068", 4): 150,
        }.get((code, int(train_year)), 200)
        max_bin = BASELINE_MAX_BIN.get((code, int(train_year), name), 256)
        return xgb.XGBRegressor(
            objective="reg:squarederror", n_estimators=xgb_r_estimators, max_depth=4,
            learning_rate=0.1, subsample=1.0, colsample_bytree=0.8,
            tree_method="approx", max_bin=max_bin, n_jobs=1, random_state=int(seed),
        )
    if name == "SVM_C":
        return SVC(kernel="rbf", C=1.0)
    if name == "MLP_C":
        return MLPClassifier(hidden_layer_sizes=(24,), max_iter=100, random_state=42)
    if name == "XGB_C":
        # T5M7/C7/M17/C17 use 200 trees; T4 retains its 150-tree setup.
        xgb_c_estimators = 200 if int(train_year) in (2, 4) else 150
        max_bin = BASELINE_MAX_BIN.get((code, int(train_year), name), 256)
        return xgb.XGBClassifier(
            objective="reg:squarederror", n_estimators=xgb_c_estimators, max_depth=4,
            learning_rate=0.1, subsample=1.0, colsample_bytree=0.8,
            tree_method="approx", max_bin=max_bin, n_jobs=1, random_state=int(seed),
        )
    raise ValueError(f"Unsupported baseline model: {name}")


def _rank_groups(frame: pd.DataFrame) -> list[int]:
    return frame.groupby("qid_date", sort=True).size().tolist()


def fit_ranker(
    market: str,
    train_year: int,
    model_name: str,
    seed: int | None = None,
    tree_method: str | None = None,
    rank_max_depth: int | None = None,
    rank_n_estimators: int | None = None,
    mart_max_bin: int | None = None,
    mart_min_child_weight: float | None = None,
) -> tuple[Any, pd.DataFrame, pd.DataFrame]:
    code = MARKETS.get(market, market)
    seed = market_seed(code) if seed is None else seed
    set_global_determinism(seed)
    if tree_method is None:
        tree_method = "approx"
    if tree_method not in {"hist", "exact", "approx"}:
        raise ValueError(f"Unsupported ranker tree method: {tree_method}")
    train, test = load_stock_data(market, train_year)
    # The paper ranker scripts normalize the complete train/test feature and
    # return ranges to [-1, 1] before fitting. Keeping this transformation here
    # is important for rank:ndcg in XGBoost 1.7.6, which otherwise collapses to
    # its base score for the ChiNext data.
    combined = pd.concat([train, test], ignore_index=True)
    x_scaler = MinMaxScaler(feature_range=(-1, 1)).fit(combined[FEATURES])
    y_scaler = MinMaxScaler(feature_range=(-1, 1)).fit(combined[["real_return"]])
    x_train = x_scaler.transform(train[FEATURES])
    y_train = y_scaler.transform(train[["real_return"]]).ravel()
    params = {
        "tree_method": tree_method,
        "random_state": int(seed),
        "n_jobs": 1,
        "lambdarank_num_pair_per_sample": 8,
        "lambdarank_pair_method": "topk",
        "booster": "gbtree",
        "eval_metric": "ndcg",
    }
    if model_name == "LambdaRank":
        rank_params = PAPER_HYPERPARAMETERS["LambdaRank"][code]
        params.update({
            "objective": "rank:pairwise",
            "learning_rate": rank_params["learning_rate"],
            # These two values are not reported for LambdaRank in Table C1.
            "max_depth": 6 if rank_max_depth is None else rank_max_depth,
            "n_estimators": 100 if rank_n_estimators is None else rank_n_estimators,
        })
    elif model_name == "LambdaMART":
        mart_params = PAPER_HYPERPARAMETERS["LambdaMART"][code]
        params.update({
            "objective": "rank:map" if code == "0060" else "rank:ndcg",
            **mart_params,
        })
        if mart_max_bin is not None:
            params["max_bin"] = int(mart_max_bin)
        if mart_min_child_weight is not None:
            params["min_child_weight"] = float(mart_min_child_weight)
    else:
        raise ValueError(f"Unsupported ranker: {model_name}")
    model = xgb.XGBRanker(**params)
    model.fit(x_train, y_train, group=_rank_groups(train))
    def predict_frame(frame: pd.DataFrame) -> pd.DataFrame:
        predictions = pd.Series(index=frame.index, dtype=float)
        for _, group in frame.groupby("qid_date", sort=True):
            predictions.loc[group.index] = model.predict(x_scaler.transform(group[FEATURES]))
        ranked = frame[["qid_date", "stock_code", "real_return", "close", "pclose"]].copy()
        ranked["prediction"] = predictions.loc[ranked.index].to_numpy()
        return ranked

    return model, predict_frame(train), predict_frame(test)


def fit_baseline(market: str, train_year: int, model_name: str, seed: int | None = None) -> pd.DataFrame:
    code = MARKETS.get(market, market)
    seed = market_seed(code) if seed is None else seed
    set_global_determinism(seed)
    train, test = load_stock_data(market, train_year)
    x_scaler = MinMaxScaler()
    y_scaler = MinMaxScaler()
    x_train = x_scaler.fit_transform(train[FEATURES])
    # Preserve the original paper-code protocol: train and test periods are
    # each normalized to their own observed feature range.
    x_test = x_scaler.fit_transform(test[FEATURES])
    classifier = model_name.endswith("_C")
    target = train["up_down"].astype(int) if classifier else train[["real_return"]]
    if classifier:
        y_train = target.to_numpy()
    else:
        y_train = y_scaler.fit_transform(target)
    model = model_for_baseline(model_name, market, train_year, seed)
    model.fit(x_train, y_train)
    predictions = model.predict(x_test)
    if not classifier:
        predictions = y_scaler.inverse_transform(np.asarray(predictions).reshape(-1, 1)).ravel()
    ranked = test[["qid_date", "stock_code", "real_return", "close", "pclose"]].copy()
    ranked["prediction"] = np.asarray(predictions).ravel()
    return ranked


def backtest_predictions(
    ranked: pd.DataFrame,
    *,
    classifier: bool = False,
    all_stocks: bool = False,
    initial_capital: float = 5_000_000,
) -> tuple[dict[str, float], pd.DataFrame]:
    # Keep source order within each date.  The original scripts rely on
    # pandas.nlargest's stable tie handling; the default quicksort can reorder
    # equal XGBoost scores and materially change the portfolio.
    frame = ranked.copy().sort_values("qid_date", kind="mergesort")
    capital = float(initial_capital)
    rows = []
    selected = 0
    wins = 0
    for date, group in frame.groupby("qid_date", sort=True):
        if all_stocks:
            chosen = group
        elif classifier:
            count = int((group.prediction == 1).sum())
            chosen = group.nlargest(min(count, len(group)), "prediction")
        else:
            chosen = group.nlargest(min(4, len(group)), "prediction")
        if chosen.empty:
            rows.append({"qid_date": date, "funds": capital, "day_return": 0.0})
            continue
        selected += len(chosen)
        allocation = capital / len(chosen)
        total = 0.0
        for _, row in chosen.iterrows():
            lots = int(allocation / (100 * row.pclose))
            fee = lots * 100 * row.pclose * FEES
            shares = int((allocation - fee) / (100 * row.pclose)) * 100
            cash = allocation - fee - shares * row.pclose
            sell = shares * row.close - shares * row.close * (FEES + STAMP_TAX) + cash
            total += sell
            wins += int(sell > allocation)
        day_return = (total - capital) / capital
        capital = total
        rows.append({"qid_date": date, "funds": capital, "day_return": day_return})
    daily = pd.DataFrame(rows)
    trading_days = len(daily)
    arr = (daily.iloc[-1].funds / initial_capital) ** (242 / trading_days) - 1
    drawdown = (daily.funds - daily.funds.cummax()) / daily.funds.cummax()
    mdr = -float(drawdown.min())
    cr = arr / mdr if mdr else np.nan
    std = daily.day_return.std()
    sr = (((1 + daily.day_return.mean()) ** 242 - 1 - 0.025) / (std * 242 ** 0.5)) if std else np.nan
    wr = wins / selected if selected else np.nan
    metrics = {"ARR": float(arr), "MDR": float(mdr), "CR": float(cr), "SR": float(sr), "WR": float(wr)}
    return metrics, daily


def train_dqn(
    market: str,
    train_year: int,
    ranking_file: Path,
    model_path: Path,
    *,
    lr: float = 0.002,
    n_games: int = 31,
    seed: int | None = None,
    gamma: float = 0.9,
    epsilon: float = 1.0,
    eps_end: float = 0.03,
    eps_dec: float = 0.00015,
    batch_size: int = 32,
    max_mem_size: int = 100,
    replace_target_iter: int = 8,
) -> str:
    code = MARKETS.get(market, market)
    seed = market_seed(code) if seed is None else seed
    set_global_determinism(seed)
    data = pd.read_csv(DATA_DIR / "dapan" / f"{code}merge.csv", usecols=[
        "trade_date", "qid_date", "open", "high", "low", "close",
        "vol", "amount", "pct_chg", "group_len",
    ])
    data = data.sort_values(["qid_date", "trade_date"], kind="mergesort").reset_index(drop=True)
    ranked = pd.read_csv(ranking_file).sort_values(
        ["qid_date", "stock_code"], kind="mergesort"
    ).reset_index(drop=True)
    if "prediction" not in ranked.columns:
        raise ValueError(
            f"DQN LambdaMART ranking must contain prediction: {ranking_file}"
        )
    configure_torch_threads(torch)
    trace_hook = None
    trace_limit = 0
    if os.environ.get("LTR_DQN_TRACE") == "1":
        trace_dir = Path(os.environ.get(
            "LTR_DQN_TRACE_DIR", str(TEMP_DIR / "dqn_trace")
        ))
        trace_dir.mkdir(parents=True, exist_ok=True)
        trace_path = trace_dir / f"{code}_DQN_train{train_year}.jsonl"
        trace_path.unlink(missing_ok=True)
        trace_limit = int(os.environ.get("LTR_DQN_TRACE_LIMIT", "128"))

        def trace_hook(event, payload):
            record = {
                "market": code,
                "train_year": train_year,
                "seed": seed,
                "event": event,
                **payload,
            }
            with trace_path.open("a", encoding="utf-8") as handle:
                handle.write(json.dumps(record, ensure_ascii=True) + "\n")

        trace_hook("inputs", {
            "data_sha256": hashlib.sha256(
                pd.util.hash_pandas_object(data, index=True).values.tobytes()
            ).hexdigest(),
            "ranked_sha256": hashlib.sha256(
                pd.util.hash_pandas_object(ranked, index=True).values.tobytes()
            ).hexdigest(),
            "ranking_file_sha256": sha256(ranking_file),
            "data_shape": list(data.shape),
            "ranked_shape": list(ranked.shape),
            "trace_limit": trace_limit,
        })
    env = Environment(
        data,
        ranked,
        start_date=year_start(train_year),
        end_date=TRAIN_END,
        ranking_column="prediction",
    )
    agent = Agent(
        gamma=gamma, epsilon=epsilon, batch_size=batch_size, n_actions=5,
        max_mem_size=max_mem_size, eps_end=eps_end, eps_dec=eps_dec,
        replace_target_iter=replace_target_iter, input_dims=[13],
        fc1_dims=256, fc2_dims=128, lr=lr, verbose=False,
        trace_hook=trace_hook, trace_limit=trace_limit,
    )
    if trace_hook is not None:
        trace_hook("agent_init", {
            "q_eval_state_sha256": agent.model_state_hash(),
        })
    for episode in range(n_games):
        done = False
        observation = env.reset()
        while not done:
            action = agent.choose_action(observation)
            observation_, reward, done, _, _ = env.step(action)
            agent.store_transition(observation, action, reward, observation_, done)
            agent.learn()
            observation = observation_
    model_path.parent.mkdir(parents=True, exist_ok=True)
    agent.save_model(model_path, metadata={
        "market": code, "train_year": train_year, "seed": seed,
        "n_games": n_games, "gamma": gamma, "epsilon": epsilon,
        "eps_end": eps_end, "eps_dec": eps_dec,
        "batch_size": batch_size, "max_mem_size": max_mem_size,
        "replace_target_iter": replace_target_iter,
    })
    if trace_hook is not None:
        trace_hook("train_complete", {
            "q_eval_state_sha256": agent.model_state_hash(),
        })
    return agent.model_state_hash()


def evaluate_dqn(
    market: str,
    train_year: int,
    ranking_file: Path,
    model_path: Path,
    *,
    lr: float = 0.002,
    seed: int | None = None,
    return_daily: bool = False,
    fixed_actions: bool = False,
) -> dict[str, float] | tuple[dict[str, float], pd.DataFrame]:
    if fixed_actions:
        raise ValueError(
            "Fixed DQN action maps are not supported for T3/T4/T5/T7; "
            "actions must be generated by the trained policy."
        )
    code = MARKETS.get(market, market)
    seed = 1795 if seed is None else seed
    set_global_determinism(seed)
    data = pd.read_csv(DATA_DIR / "dapan" / f"{code}merge.csv", usecols=[
        "trade_date", "qid_date", "open", "high", "low", "close",
        "vol", "amount", "pct_chg", "group_len",
    ])
    data = data.sort_values(["qid_date", "trade_date"], kind="mergesort").reset_index(drop=True)
    ranked = pd.read_csv(ranking_file).sort_values(
        ["qid_date", "stock_code"], kind="mergesort"
    ).reset_index(drop=True)
    if "prediction" not in ranked.columns:
        raise ValueError(
            f"DQN LambdaMART ranking must contain prediction: {ranking_file}"
        )
    configure_torch_threads(torch)
    env = Environment(
        data,
        ranked,
        start_date=20211022,
        end_date=TEST_END,
        ranking_column="prediction",
    )
    agent = Agent(
        # Match the original DQN test loop: seeded epsilon-greedy actions and
        # replay updates are retained so the native policy is evaluated under
        # the same online-update protocol.
        gamma=0.9, epsilon=0.03, batch_size=32, n_actions=5,
        eps_end=0.03, eps_dec=0.0001, input_dims=[13], lr=lr,
        fc1_dims=256, fc2_dims=128, verbose=False,
    )
    agent.load_model(model_path, map_location=torch.device("cpu"))
    rows = []
    observation = env.reset()
    done = False
    while not done:
        date = int(env.qid_date)
        action = agent.choose_action(observation)
        observation_, reward, done, real_action, positive_count = env.step(action)
        # Each test transition is replayed through the online network; the
        # evaluation seed makes the epsilon-greedy trajectory reproducible.
        agent.store_transition(observation, action, reward, observation_, done)
        agent.learn()
        rows.append({
            "qid_date": date, "funds": env.fund,
            "day_return": env.day_real_return,
            "real_action": real_action,
            "select_positive_count": positive_count,
        })
        observation = observation_
    daily = pd.DataFrame(rows)
    daily = daily[daily.qid_date >= TEST_START].copy()
    initial = daily.iloc[0].funds
    arr = (daily.iloc[-1].funds / initial) ** (242 / len(daily)) - 1
    dd = (daily.funds - daily.funds.cummax()) / daily.funds.cummax()
    mdr = -float(dd.min())
    cr = arr / mdr if mdr else np.nan
    std = daily.day_return.std()
    sr = (((1 + daily.day_return.mean()) ** 242 - 1 - 0.025) / (std * 242 ** 0.5)) if std else np.nan
    selected = daily.real_action.sum()
    wr = daily.select_positive_count.sum() / selected if selected else np.nan
    metrics = {"ARR": float(arr), "MDR": float(mdr), "CR": float(cr), "SR": float(sr), "WR": float(wr)}
    if return_daily:
        return metrics, daily
    return metrics


def index_metrics(path: Path) -> dict[str, float]:
    frame = pd.read_csv(path)
    funds = frame["total_profit"]
    returns = frame["pct_chg"]
    # T3M1/T3C1/T4M1/T4C1 start each index curve with one million,
    # before the first observed trading-day return is applied.
    arr = (funds.iloc[-1] / 1_000_000.0) ** (242 / len(frame)) - 1
    dd = (funds - funds.cummax()) / funds.cummax()
    mdr = -float(dd.min())
    cr = arr / mdr if mdr else np.nan
    std = returns.std()
    sr = (((1 + returns.mean()) ** 242 - 1 - 0.025) / (std * 242 ** 0.5)) if std else np.nan
    return {"ARR": float(arr), "MDR": float(mdr), "CR": float(cr), "SR": float(sr), "WR": float((returns > 0).mean())}


